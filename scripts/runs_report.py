"""Write docs/SIMULATION-RUNS.md from the run exports in data/runs/*/summary.json."""

from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "data" / "runs"
TARGET = ROOT / "docs" / "SIMULATION-RUNS.md"
RELEASE = "https://github.com/AnuarH16/analitica-reparto-clickhouse/releases/tag/simulation-runs-2026-11-01"
TABLES = ("courier_positions", "customer_activity", "app_events", "order_events", "customer_orders")


def moment(text: str) -> datetime:
    return datetime.fromisoformat(text[:19])


def duration(summary: dict) -> str:
    times = [table for table in summary["tables"].values() if table["rows"]]
    seconds = (max(moment(t["last_event"]) for t in times) - min(moment(t["first_event"]) for t in times)).total_seconds()
    hours, minutes = divmod(round(seconds / 60), 60)
    return f"{hours} h {minutes:02d} min" if hours else f"{minutes} min" if minutes else "< 1 min"


def main() -> None:
    summaries = [(json.loads(path.read_text(encoding="utf-8")), path.parent.name) for path in RUNS.glob("*/summary.json")]
    summaries.sort(key=lambda item: min(t["first_event"] for t in item[0]["tables"].values() if t["rows"]))
    total_rows = sum(t["rows"] for summary, _ in summaries for t in summary["tables"].values())
    total_bytes = sum(t["bytes"] for summary, _ in summaries for t in summary["tables"].values())
    lines = [
        "# Simulation runs",
        "",
        "Every Delivery Atlas simulation run kept on the demo server (Anuar's computer), generated by "
        "`python scripts/runs_report.py` from `data/runs/*/summary.json`. Each run was exported with "
        "`python scripts/export_run.py <run_id>` after stopping it and waiting for the queue to reach pending 0: "
        "five gzip CSV files (one per table, `FINAL`, ordered by `event_time`) plus `summary.json`.",
        "",
        f"**{len(summaries)} runs, {total_rows:,} rows, {total_bytes / 1e9:.2f} GB compressed.** "
        f"The exports are not in Git: download them from the [GitHub release]({RELEASE}) (one `.tar` per run). "
        "All the data is fictional and synthetic; the downloaded Criteo and Glovo datasets are not included.",
        "",
        "Times are UTC. Customers and couriers are the distinct IDs that appear in the run; "
        "AI customers are those with at least one decision taken by the local model (`decision_mode = 'ollama'`), "
        "which stops after 120 model calls per run.",
        "",
        "| Run | Start (UTC) | Duration | Customers (AI) | Couriers | GPS positions | Customer actions | Browsing events "
        "| Order events | Orders | Delivered | Total rows |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for summary, folder in summaries:
        tables, people = summary["tables"], summary.get("participants", {})
        start = min(t["first_event"] for t in tables.values() if t["rows"])[:16]
        delivered = sum(s["orders"] for s in summary["orders_by_status"] if s["status"] == "delivered")
        counts = " | ".join(f"{tables[name]['rows']:,}" for name in TABLES)
        lines.append(f"| `{folder}` | {start} | {duration(summary)} | {people.get('customers', 0):,} "
                     f"({people.get('ai_customers', 0)}) | {people.get('couriers', 0):,} | {counts} | {delivered:,} "
                     f"| {sum(t['rows'] for t in tables.values()):,} |")
    lines += [
        "",
        "Column to table: GPS positions = `courier_positions`, customer actions = `customer_activity`, "
        "browsing events = `app_events`, order events = `order_events`, orders = `customer_orders`.",
        "",
        "## Notes on the runs",
        "",
        "- **19–22 October:** first runs with 24 simulated customers and 12 couriers, then hybrid runs "
        "(3 AI customers + simulated traffic). Short runs were tests of the AI agents or were stopped to update the server.",
        "- **28–30 October:** hybrid runs with 100 customers and 50 couriers prepared for the checkpoint presentation; "
        "`2026-10-28_a12236a9` ran for almost two days.",
        "- **31 October (big-data run):** two Atlas APIs writing to the same ClickHouse for 8 hours, each with "
        "500 customers, 150 couriers and a 1-second tick: `2026-10-31_4f297d43` on port 8001 (hybrid, seed 31) and "
        "`2026-10-31_6bf38221` on a second container on port 18001 (traffic only, seed 62). Together about 13.4 million "
        "rows, roughly 1.7 million per hour. ClickHouse used about 40 % CPU when checked, and both queues drained to 0 when stopped. "
        "`scripts/simulation_watchdog.sh` was ready to reopen Docker Desktop and restart the runs, but no restart was needed. "
        "`2026-10-31_ce8625ad` is a one-minute run that the watchdog started by mistake after the planned stop.",
        "- **1 November:** the same two-API setup (`2026-11-01_2d08b7a9` hybrid, `2026-11-01_31fdac6e` traffic) stopped "
        "after 23 minutes, when Docker Desktop closed and the watchdog closed with the session that ran it. "
        "The queues still published everything once Docker was back.",
        "- **3 November (largest run):** the same setup again for about 11 hours, from 02:20 to 13:25 UTC: "
        "`2026-11-03_70861ccd` (hybrid, seed 1103) and `2026-11-03_592f4a72` (traffic only, seed 1104), together "
        "about 18.5 million rows. The watchdog ran the whole time without needing to restart anything, and the rows "
        "exported for each run equal the events its API accepted.",
        "- The second API was a manual `docker run` of the Atlas image on port 18001 with its own queue volume. "
        "From Git Bash, prefix that command with `MSYS_NO_PATHCONV=1`; otherwise Git Bash rewrites "
        "`ATLAS_QUEUE_PATH=/state/outbox.sqlite` to a Windows path and the queue is not kept on the volume.",
        "",
    ]
    TARGET.write_bytes("\n".join(lines).encode())
    print(f"Wrote {TARGET.relative_to(ROOT)}: {len(summaries)} runs, {total_rows:,} rows")


if __name__ == "__main__":
    main()
